"""Offline tests for the complete vector-search and hydration service."""

from typing import Any

import pytest

from backend.embedding.models import (
    EmbeddingBatch,
    EmbeddingInputPurpose,
    VectorSearchHit,
)
from backend.pipeline.configs import EmbeddingConfig, RetrievalConfig
from backend.retrieval.service import (
    InvalidRetrievalArtifactError,
    retrieve_chunks,
)


class FakeEmbeddingProvider:
    """Return one deterministic query vector and record provider inputs."""

    identifier = "test-provider"
    version = "1"

    def __init__(self) -> None:
        """Initialize an empty record of query embedding calls.

        Args:
            None.

        Returns:
            None. Calls begin empty for later assertions.
        """
        self.calls: list[tuple[str, list[str], EmbeddingInputPurpose]] = []

    def input_policy_version(self, model: str) -> str:
        """Return the input policy expected by the compatible test index.

        Args:
            model: Provider model selected by the retrieval configuration.

        Returns:
            Stable test input-policy identity.
        """
        return "test-policy-v1"

    def embed(
        self,
        model: str,
        texts: list[str],
        purpose: EmbeddingInputPurpose,
    ) -> EmbeddingBatch:
        """Record the request and return one fixed three-dimensional vector.

        Args:
            model: Provider model selected for the query.
            texts: Normalized one-question embedding input.
            purpose: Semantic query role supplied to the provider.

        Returns:
            Deterministic query embedding batch.
        """
        self.calls.append((model, texts, purpose))
        return EmbeddingBatch(vectors=((1.0, 2.0, 3.0),), dimensions=3)


class FakeVectorStore:
    """Return deterministic lightweight vector hits and record the search."""

    identifier = "test-store"
    version = "1"

    def __init__(self, hits: tuple[VectorSearchHit, ...]) -> None:
        """Configure the vector hits returned by the fake adapter.

        Args:
            hits: Ranked lightweight vector matches returned by query.

        Returns:
            None. Calls begin empty for later assertions.
        """
        self.hits = hits
        self.calls: list[tuple[str, list[float], int]] = []

    def query(
        self,
        collection_name: str,
        vector: list[float],
        top_k: int,
    ) -> tuple[VectorSearchHit, ...]:
        """Record one nearest-neighbor query and return configured hits.

        Args:
            collection_name: Exact compatible collection being searched.
            vector: Query vector generated by the embedding provider.
            top_k: Result limit clamped to the index vector count.

        Returns:
            Configured lightweight vector hits.
        """
        self.calls.append((collection_name, vector, top_k))
        return self.hits


