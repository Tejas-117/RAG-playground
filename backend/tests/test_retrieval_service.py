def _chunk(chunk_id: str, ordinal: int, text: str) -> dict[str, Any]:
    """Create one materialized immutable chunk returned by the test loader.

    Args:
        chunk_id: Stable chunk identifier requested by hydration.
        ordinal: Zero-based chunk order in its source document.
        text: Exact embedded text owned by the chunk.

    Returns:
        Complete chunk dictionary matching the hydration boundary.
    """
    return {
        "id": chunk_id,
        "source_document_id": "document-1",
        "ordinal": ordinal,
        "text": text,
        "character_start_offset": ordinal * 10,
        "character_end_offset": (ordinal + 1) * 10,
        "token_start_offset": ordinal * 2,
        "token_end_offset": (ordinal + 1) * 2,
        "page_start": ordinal + 1,
        "page_end": ordinal + 1,
        "section_path": None,
        "source_metadata": {"block_ordinals": [ordinal]},
    }


def test_retrieve_chunks_searches_then_hydrates_in_rank_order() -> None:
    """Verify the service coordinates query embedding, search, and hydration.

    Args:
        None.

    Returns:
        None. Assertions cover dependency inputs and fully hydrated ordering.
    """
    provider = FakeEmbeddingProvider()
    vector_store = FakeVectorStore(
        (
            VectorSearchHit("chunk-2", 0.1),
            VectorSearchHit("chunk-1", 0.2),
        )
    )
    chunks = {
        "chunk-1": _chunk("chunk-1", 0, "First"),
        "chunk-2": _chunk("chunk-2", 1, "Second"),
    }
    loader_calls: list[tuple[str, tuple[str, ...]]] = []

    # The injected loader records artifact scoping without touching SQLite.
    def load_chunks(
        chunk_set_id: str,
        chunk_ids: tuple[str, ...],
    ) -> dict[str, dict[str, Any]]:
        """Return requested test chunks and record the scoped batch lookup.

        Args:
            chunk_set_id: Exact chunk set supplied by the vector index.
            chunk_ids: Ranked stable IDs returned by vector search.

        Returns:
            Requested chunk records keyed by stable ID.
        """
        loader_calls.append((chunk_set_id, chunk_ids))
        return {chunk_id: chunks[chunk_id] for chunk_id in chunk_ids}

    hydrated = retrieve_chunks(
        "  What changed?  ",
        RetrievalConfig(top_k=10),
        _embedding_config(),
        _vector_index(),
        provider,
        vector_store,
        load_chunks,
    )

    assert provider.calls == [
        (
            "nomic-embed-text",
            ["What changed?"],
            EmbeddingInputPurpose.QUERY,
        )
    ]
    assert vector_store.calls == [("rag_idx_test", [1.0, 2.0, 3.0], 2)]
    assert loader_calls == [("chunk-set-1", ("chunk-2", "chunk-1"))]
    assert [(hit.rank, hit.chunk_id, hit.text) for hit in hydrated] == [
        (1, "chunk-2", "Second"),
        (2, "chunk-1", "First"),
    ]


def test_retrieve_chunks_allows_empty_search_results() -> None:
    """Verify no-hit vector searches return an empty hydrated result.

    Args:
        None.

    Returns:
        None. Assertions verify the chunk loader is not called.
    """
    provider = FakeEmbeddingProvider()
    vector_store = FakeVectorStore(())

    # A failing loader proves hydration short-circuits empty search results.
    def unexpected_loader(
        chunk_set_id: str,
        chunk_ids: tuple[str, ...],
    ) -> dict[str, dict[str, Any]]:
        """Fail if an empty vector result attempts a database lookup.

        Args:
            chunk_set_id: Unused artifact identifier.
            chunk_ids: Unused empty chunk identifier tuple.

        Returns:
            No return is expected because the function always fails.
        """
        raise AssertionError("The chunk loader should not be called.")

    hydrated = retrieve_chunks(
        "Question",
        RetrievalConfig(top_k=2),
        _embedding_config(),
        _vector_index(),
        provider,
        vector_store,
        unexpected_loader,
    )

    assert hydrated == ()


def test_retrieve_chunks_rejects_missing_chunk_set_before_search() -> None:
    """Verify an index without hydration provenance fails before provider work.

    Args:
        None.

    Returns:
        None. Assertions verify the provider and vector store remain unused.
    """
    provider = FakeEmbeddingProvider()
    vector_store = FakeVectorStore(())

    with pytest.raises(InvalidRetrievalArtifactError, match="chunk-set"):
        retrieve_chunks(
            "Question",
            RetrievalConfig(top_k=2),
            _embedding_config(),
            _vector_index(chunk_set_id=""),
            provider,
            vector_store,
        )

    assert provider.calls == []
    assert vector_store.calls == []
