"use client";

import {
  type MouseEvent,
  type SyntheticEvent,
  useEffect,
  useRef,
} from "react";
import {
  FiAlertCircle,
  FiCheck,
  FiClock,
  FiDatabase,
  FiRefreshCw,
  FiX,
} from "react-icons/fi";
import {
  type RunExecutionView,
  type RunStageStatus,
} from "@/lib/run-execution";

/** Values and actions required by the experiment execution modal. */
type ExperimentRunModalProps = {
  execution: RunExecutionView;
  isRetrying: boolean;
  onClose: () => void;
  onRetry: () => void;
};

/**
 * Selects the accessible status label shown for one execution stage.
 *
 * @param status - Current presentation state of the stage.
 * @returns A concise user-facing status label.
 */
function getStageStatusLabel(status: RunStageStatus): string {
  // Translate internal stage states into consistent interface language.
  if (status === "running") {
    return "Running";
  }

  // Confirm work that the backend has completed successfully.
  if (status === "completed") {
    return "Complete";
  }

  // Identify the pipeline stage that stopped the run.
  if (status === "failed") {
    return "Failed";
  }

  return "Not available yet";
}

/**
 * Displays real run progress and reserved future stages in a focused modal.
 *
 * @param props - Current execution state and modal actions.
 * @returns A native modal dialog containing the execution trace and result details.
 */
export default function ExperimentRunModal({
  execution,
  isRetrying,
  onClose,
  onRetry,
}: ExperimentRunModalProps) {
  // Stores the native dialog used for top-layer focus and backdrop behavior.
  const dialogRef = useRef<HTMLDialogElement | null>(null);

  // Opens the dialog modally and restores the previous focus when it unmounts.
  useEffect(() => {
    const dialog = dialogRef.current;
    const previouslyFocusedElement = document.activeElement as HTMLElement | null;

    // Place the execution inspector in the browser top layer when it first renders.
    if (dialog && !dialog.open) {
      dialog.showModal();
      dialog.focus();
    }

    return () => {
      // Close any remaining native dialog state before restoring the triggering control.
      if (dialog?.open) {
        dialog.close();
      }

      previouslyFocusedElement?.focus();
    };
  }, []);

  // Derive modal language and controls from the overall execution outcome.
  const isRunning = execution.status === "running";
  const isCompleted = execution.status === "completed";
  const isFailed = execution.status === "failed";
  const statusLabel = isRunning
    ? "Experiment running"
    : isCompleted
      ? "Chunking complete"
      : "Experiment stopped";

  /**
   * Requests a native dialog close after the run is no longer active.
   *
   * @returns Nothing. The dialog close event notifies the parent component.
   */
  function closeModal(): void {
    // Keep active execution visible because closing does not cancel the backend request.
    if (!isRunning) {
      dialogRef.current?.close();
    }
  }

  /**
   * Handles Escape requests generated by the native dialog.
   *
   * @param event - Cancel event emitted before the dialog closes.
   * @returns Nothing. Active runs remain open; finished runs close normally.
   */
  function handleCancel(event: SyntheticEvent<HTMLDialogElement>): void {
    // Prevent Escape from hiding a request that is still executing.
    if (isRunning) {
      event.preventDefault();
    }
  }

  /**
   * Closes the dialog when a user clicks the empty backdrop area.
   *
   * @param event - Pointer event received by the outer dialog element.
   * @returns Nothing. Clicks inside the inspector leave it open.
   */
  function handleBackdropClick(event: MouseEvent<HTMLDialogElement>): void {
    // Native dialog backdrop clicks target the dialog rather than its inner content.
    if (event.target === event.currentTarget) {
      closeModal();
    }
  }

  return (
    /* The native dialog supplies a focus trap while CSS creates the blurred workbench backdrop. */
    <dialog
      aria-busy={isRunning}
      aria-labelledby="run-execution-heading"
      className="run-modal"
      onCancel={handleCancel}
      onClick={handleBackdropClick}
      onClose={onClose}
      ref={dialogRef}
    >
      {/* The modal shell resembles a compact pipeline inspector rather than a generic alert. */}
      <div
        className={`
          run-modal-shell mx-auto w-[calc(100vw-2rem)] max-w-4xl overflow-hidden
          rounded-md border border-white/15 bg-[var(--white)] text-[var(--charcoal)]
        `}
      >
        {/* The header anchors execution state, corpus provenance, and the close action. */}
        <header
          className={`
            relative overflow-hidden bg-[var(--charcoal)] px-5 py-5 text-[var(--white)]
            sm:px-7 sm:py-6
          `}
        >
          <div aria-hidden="true" className="run-modal-header-grid" />
          <div className="relative flex items-start justify-between gap-5">
            <div className="flex min-w-0 items-start gap-3">
              {/* The status icon communicates outcome without relying on color alone. */}
              {isRunning ? (
                <span
                  aria-hidden="true"
                  className={`
                    run-status-spinner mt-1 size-5 shrink-0 rounded-full border-2
                    border-white/30 border-t-white
                  `}
                />
              ) : isCompleted ? (
                <span
                  className={`
                    mt-0.5 flex size-6 shrink-0 items-center justify-center rounded-full
                    bg-white text-[var(--charcoal)]
                  `}
                >
                  <FiCheck aria-hidden="true" className="size-4" />
                </span>
              ) : (
                <FiAlertCircle aria-hidden="true" className="mt-0.5 size-5 shrink-0" />
              )}
              <div className="min-w-0">
                <p
                  className={`
                    font-mono text-[10px] font-bold uppercase tracking-[0.18em]
                    text-white/55
                  `}
                >
                  Run inspector
                </p>
                <h2
                  className="mt-1 text-2xl font-bold tracking-[-0.045em] sm:text-3xl"
                  id="run-execution-heading"
                >
                  {statusLabel}
                </h2>
                <p className="mt-2 truncate text-xs leading-5 text-white/65">
                  Source · {execution.corpusName}
                </p>
              </div>
            </div>

            {/* Finished runs provide an explicit close action in addition to Escape. */}
            {!isRunning ? (
              <button
                aria-label="Close run details"
                className={`
                  flex size-9 shrink-0 items-center justify-center rounded border
                  border-white/20 bg-white/5 text-white transition-colors
                  hover:bg-white/15 focus-visible:outline-none focus-visible:ring-2
                  focus-visible:ring-white
                `}
                onClick={closeModal}
                type="button"
              >
                <FiX aria-hidden="true" className="size-4" />
              </button>
            ) : (
              <span
                className={`
                  shrink-0 rounded-full border border-white/20 px-3 py-1.5 font-mono
                  text-[9px] font-bold uppercase tracking-[0.12em] text-white/65
                `}
              >
                Keep open
              </span>
            )}
          </div>
        </header>

        {/* The content separates the ordered trace from concrete run measurements. */}
        <div className="grid max-h-[min(70vh,620px)] overflow-y-auto lg:grid-cols-[1fr_280px]">
          {/* The vertical signal trace makes stage order easy to scan. */}
          <section className="border-b border-[var(--border-soft)] px-5 py-6 sm:px-7 lg:border-b-0">
            <p
              className={`
                font-mono text-[9px] font-bold uppercase tracking-[0.16em]
                text-[var(--muted-text)]
              `}
            >
              Pipeline trace
            </p>
            <ol className="mt-5">
              {execution.stages.map((stage, index) => {
                const isStageRunning = stage.status === "running";
                const isStageCompleted = stage.status === "completed";
                const isStageFailed = stage.status === "failed";
                const isLastStage = index === execution.stages.length - 1;

                return (
                  /* Each row owns one ordered stage, state marker, and connecting signal line. */
                  <li className="relative grid grid-cols-[28px_1fr] gap-3" key={stage.id}>
                    {/* The line connects only real neighboring stages in execution order. */}
                    {!isLastStage ? (
                      <span
                        aria-hidden="true"
                        className={`
                          absolute left-[13px] top-7 h-[calc(100%-28px)] w-px
                          bg-[var(--border-subtle)]
                        `}
                      />
                    ) : null}
                    <span
                      className={`
                        relative z-10 flex size-7 items-center justify-center rounded-full
                        border font-mono text-[9px] font-bold
                        ${
                          isStageCompleted
                            ? `border-[var(--charcoal)] bg-[var(--charcoal)]
                              text-[var(--white)]`
                            : isStageFailed
                              ? `border-[var(--toast-error-text)]
                                bg-[var(--toast-error-surface)]
                                text-[var(--toast-error-text)]`
                              : isStageRunning
                                ? "border-[var(--charcoal)] bg-[var(--white)]"
                                : `border-[var(--border-subtle)] bg-[var(--panel-surface)]
                                  text-[var(--muted-text)]`
                        }
                      `}
                    >
                      {/* Marker content distinguishes active, successful, and reserved stages. */}
                      {isStageRunning ? (
                        <span
                          aria-hidden="true"
                          className={`
                            run-status-spinner size-3 rounded-full border
                            border-current border-t-transparent
                          `}
                        />
                      ) : isStageCompleted ? (
                        <FiCheck aria-hidden="true" className="size-3.5" />
                      ) : (
                        index + 1
                      )}
                    </span>
                    <div className={`min-w-0 ${isLastStage ? "pb-0" : "pb-5"}`}>
                      <div className="flex flex-wrap items-baseline justify-between gap-2">
                        <p className="text-sm font-bold">{stage.label}</p>
                        <p className="font-mono text-[9px] uppercase text-[var(--muted-text)]">
                          {getStageStatusLabel(stage.status)}
                        </p>
                      </div>
                      <p className="mt-1 text-xs leading-5 text-[var(--muted-text)]">
                        {stage.description}
                      </p>
                    </div>
                  </li>
                );
              })}
            </ol>
          </section>

          {/* The result ledger shows persisted facts without competing with the trace. */}
          <aside
            className={`
              bg-[var(--panel-surface)] px-5 py-6 sm:px-7 lg:border-l
              lg:border-[var(--border-soft)]
            `}
          >
            <p
              className={`
                font-mono text-[9px] font-bold uppercase tracking-[0.16em]
                text-[var(--muted-text)]
              `}
            >
              Run record
            </p>

            {/* Running state explains why measurements are not available yet. */}
            {isRunning ? (
              <div className="mt-5 border-l-2 border-[var(--charcoal)] pl-4">
                <p className="text-sm font-bold">Building chunk artifact</p>
                <p className="mt-1 text-xs leading-5 text-[var(--muted-text)]">
                  Measurements will appear when the backend finishes this stage.
                </p>
              </div>
            ) : null}

            {/* Completed runs expose chunking provenance and elapsed execution time. */}
            {isCompleted && execution.chunking ? (
              <dl className="mt-5 divide-y divide-[var(--border-subtle)]">
                <div className="pb-4">
                  <dt className="font-mono text-[9px] uppercase text-[var(--muted-text)]">
                    Chunks
                  </dt>
                  <dd className="mt-1 text-3xl font-bold tracking-[-0.05em]">
                    {execution.chunking.chunkCount.toLocaleString()}
                  </dd>
                </div>
                <div className="flex items-center justify-between gap-3 py-4">
                  <dt className="text-xs text-[var(--muted-text)]">Artifact</dt>
                  <dd className="flex items-center gap-2 text-xs font-bold">
                    <FiDatabase aria-hidden="true" className="size-3.5" />
                    {execution.chunking.reused ? "Reused" : "Created"}
                  </dd>
                </div>
                <div className="flex items-center justify-between gap-3 py-4">
                  <dt className="text-xs text-[var(--muted-text)]">Duration</dt>
                  <dd className="flex items-center gap-2 text-xs font-bold">
                    <FiClock aria-hidden="true" className="size-3.5" />
                    {execution.durationMs?.toLocaleString() ?? 0} ms
                  </dd>
                </div>
                <div className="pt-4">
                  <dt className="text-xs text-[var(--muted-text)]">Run ID</dt>
                  <dd
                    className="mt-2 break-all font-mono text-[10px] leading-4"
                    title={execution.runId}
                  >
                    {execution.runId}
                  </dd>
                </div>
              </dl>
            ) : null}

            {/* Failed runs explain the interruption and keep its recovery action nearby. */}
            {isFailed ? (
              <div className="mt-5" role="alert">
                <div className="border-l-2 border-[var(--toast-error-text)] pl-4">
                  <p className="text-sm font-bold text-[var(--toast-error-text)]">
                    The run could not finish
                  </p>
                  <p className="mt-1 text-xs leading-5 text-[var(--toast-error-text)]">
                    {execution.errorMessage}
                  </p>
                </div>
                {execution.runId ? (
                  <p className="mt-4 break-all font-mono text-[10px] text-[var(--muted-text)]">
                    Run ID: {execution.runId}
                  </p>
                ) : null}
                <button
                  className={`
                    mt-5 inline-flex w-full items-center justify-center gap-2 rounded
                    bg-[var(--charcoal)] px-4 py-2.5 text-xs font-bold text-[var(--white)]
                    transition-colors hover:bg-[var(--primary-hover)]
                    focus-visible:outline-none focus-visible:ring-2
                    focus-visible:ring-[var(--charcoal)] focus-visible:ring-offset-2
                    disabled:cursor-not-allowed disabled:opacity-50
                  `}
                  disabled={isRetrying}
                  onClick={onRetry}
                  type="button"
                >
                  <FiRefreshCw
                    aria-hidden="true"
                    className={`size-3.5 ${isRetrying ? "run-status-spinner" : ""}`}
                  />
                  {isRetrying ? "Retrying…" : "Retry run"}
                </button>
              </div>
            ) : null}
          </aside>
        </div>
      </div>
    </dialog>
  );
}
